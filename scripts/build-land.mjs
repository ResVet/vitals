// Rasterizes Natural Earth land (via world-atlas) into a 0.5 degree bitmask
// and writes it as a base64 string the globe generator reads in a worker.
// d3-geo does the drawing in headless Chromium because it clips rings at the
// antimeridian properly, which a naive scanline fill does not.
// Run with: npm run land
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';

const W = 720; // 0.5 deg columns
const H = 360; // 0.5 deg rows
const read = (p) => readFileSync(new URL(p, import.meta.url), 'utf8');

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
});
const page = await browser.newPage();
await page.setContent('<canvas></canvas>');
await page.addScriptTag({ content: read('../node_modules/d3-array/dist/d3-array.min.js') });
await page.addScriptTag({ content: read('../node_modules/d3-geo/dist/d3-geo.min.js') });
await page.addScriptTag({ content: read('../node_modules/topojson-client/dist/topojson-client.min.js') });

const cells = await page.evaluate(
  ({ topo, W, H }) => {
    const SS = 4; // supersample, then threshold at 50% coverage
    const canvas = document.querySelector('canvas');
    canvas.width = W * SS;
    canvas.height = H * SS;
    const ctx = canvas.getContext('2d');
    const land = topojson.feature(topo, topo.objects.land);
    const projection = d3.geoEquirectangular().scale((W * SS) / (2 * Math.PI)).translate([(W * SS) / 2, (H * SS) / 2]);
    const path = d3.geoPath(projection, ctx);
    ctx.fillStyle = '#fff';
    ctx.beginPath();
    path(land);
    ctx.fill();
    const img = ctx.getImageData(0, 0, W * SS, H * SS).data;
    const out = new Array(W * H).fill(0);
    for (let y = 0; y < H; y++) {
      for (let x = 0; x < W; x++) {
        let sum = 0;
        for (let sy = 0; sy < SS; sy++)
          for (let sx = 0; sx < SS; sx++) sum += img[((y * SS + sy) * W * SS + (x * SS + sx)) * 4];
        out[y * W + x] = sum / (SS * SS * 255) >= 0.5 ? 1 : 0;
      }
    }
    return out;
  },
  { topo: JSON.parse(read('../node_modules/world-atlas/land-50m.json')), W, H }
);
await browser.close();

const bits = new Uint8Array((W * H) >> 3);
let filled = 0;
cells.forEach((v, i) => {
  if (v) {
    bits[i >> 3] |= 1 << (i & 7);
    filled++;
  }
});

const b64 = Buffer.from(bits).toString('base64');
writeFileSync(
  new URL('../src/gl/shapes/landmask.js', import.meta.url),
  `// Generated by scripts/build-land.mjs from Natural Earth 1:50m land (public domain).\n` +
    `// ${W}x${H} cells of 0.5 degrees. Row 0 starts at 90N, column 0 at 180W. One bit per cell.\n` +
    `export const LAND_W = ${W};\nexport const LAND_H = ${H};\nexport const LAND_BITS = '${b64}';\n`
);

const pgm = Buffer.alloc(W * H);
cells.forEach((v, i) => (pgm[i] = v ? 255 : 0));
writeFileSync(new URL('./.land-preview.pgm', import.meta.url), Buffer.concat([Buffer.from(`P5 ${W} ${H} 255\n`), pgm]));
console.log(`land cells: ${filled} of ${W * H} (${((filled / (W * H)) * 100).toFixed(1)}%)`);
